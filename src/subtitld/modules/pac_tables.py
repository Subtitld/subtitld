"""The character tables of Screen's PAC code pages, for modules.pac.

Screen never published PAC, and these tables are what is known of it: the
ones Subtitle Edit worked out from real files over the years (libse,
SubtitleFormats/Pac.cs, GPL-3 as Subtitld is), kept here as data, with
their quirks, so a file reads as the tools subtitlers use read it.

A key is the bytes a character takes, read as one big-endian number: 0x41
is the byte 41, 0xe241 the two bytes E2 41 (an acute, then the letter it
goes on), 0xe22041 three. modules.pac turns them into bytes.

    LATIN       the Latin code page: ASCII with a few places taken (as the
                Nordic ISO 646 sets have them: Æ Ø æ ø), the accents E0 to
                EC written before their letter, some letters after which
                8A is a macron or E2 a caron; whatever is not here is
                ISO 8859-1 (8859-2 for Latin Czech, 8859-9 for Turkish)
    TURKISH     what the Turkish Latin page reads otherwise: E7 and EA a
                breve
    PORTUGUESE  what the Portuguese Latin page reads otherwise: its two
                dashes swapped
    GREEK       Greek on the places of the ASCII letters, the Latin letters
                moved to 8C-C5; E2 an acute, E5 a diaeresis before a letter
    CYRILLIC    Cyrillic on the keys of a Russian typewriter (ЙЦУКЕН laid
                over QWERTY: F is А, D is В), the Latin letters moved
    HEBREW      the letters from A0 (ISO 8859-8's, 64 places lower), the
                vowel points from 80; ASCII as it is
    ARABIC      the letters from 80; the vowel marks before the letter they
                go on (ARABIC_BEFORE_LETTER); ASCII as it is but for ? % , ;
    THAI        TIS-620's consonants from A1, its leading vowels and marks
                moved to 80; ASCII as it is

LATIN_PRIORITY says which of two readings wins where bytes could be read
either way (L E2 is Ľ, unless E2 begins an accented letter itself; E2 20
is an acute alone): a reading of higher priority is taken first; those
not listed are 2.
"""


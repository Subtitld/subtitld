"""USF (Universal Subtitle Format) reader/writer.

USF is XML: <USFSubtitles>, its <metadata>, named <styles>, and one
<subtitles> block for each language, of <subtitle start=... stop=...>
holding a <text>. Subtitld keeps its projects in it (USFX is a USF with
the project's assets), with speakers, their colours and voices, and dubs.

Reading takes what other tools write too: the encoding the XML declares;
"duration" for a missing "stop", and times as seconds alone; the
italic, bold (or weight), underline and colour of the named style a
<text> uses, and its position's alignment, where the text says none;
<font italic="yes" bold="yes" underline="yes">, as USF's own list of
plans has it, besides <i>, <b>, <u> and <font color>; several <text>s
in one subtitle as its lines (in the first's place); the subtitles
sorted by start; each language's block matched to the first's by time,
not by place; ISO 639-2 language codes ("eng"), and the
language's name the element holds ("Portuguese (Brazil)").

Writing gives USF 1.0 as Subtitld reads it back: languages by their ISO
639-2 codes, as the specification asks ("por"), each <language> holding
the language's name ("Portuguese (Brazil)"), which tells Subtitld which
of a code's languages it is when it reads the file again. No style
overrides the player's own default look.
"""


import base64
import bisect
import os

from bs4 import BeautifulSoup, NavigableString

from subtitld.modules import markup


# subtitld.cc names where a file came from in its own namespace:
# <subtitldcc:origin share-id="Xk3pQ9aZ2bT" version="3"/> inside <metadata>,
# and each subtitle's stable ID as <subtitle subtitldcc:id="…">.
SUBTITLDCC_NAMESPACE = 'https://subtitld.cc/ns/usf/1'
SUBTITLDCC_ID = 'subtitldcc:id'

USF_BASE_MARKUP = '''<!-- USF file generated by Subtitld -->
<USFSubtitles version="1.0">
    <metadata></metadata>
    <styles></styles>
</USFSubtitles>'''


# USF 1.1 formats a subtitle's text as XHTML does: <i>, <b>, <u> and
# <font color="#AARRGGBB">, with <br/> between lines; <s> is the strikeout
# its to-do list plans. The text's position is the <text> element's
# "alignment" (TopLeft ... BottomRight). Subtitld keeps formatting as
# SRT-style tags (modules.markup), so these are read into them and written
# from them.
_INLINE = ('i', 'b', 'u', 's')

# ISO 639-2 codes for Subtitld's languages, as Matroska writes them (the
# bibliographic ones: "fre", "ger"); the terminologic ones ("fra", "deu")
# are read too.
ISO639_2 = {
    'af': 'afr', 'am': 'amh', 'ar': 'ara', 'az': 'aze', 'bg': 'bul', 'bn': 'ben', 'ca': 'cat', 'cmn': 'chi',
    'cs': 'cze', 'da': 'dan', 'de': 'ger', 'el': 'gre', 'en': 'eng', 'es': 'spa', 'eu': 'baq', 'fa': 'per',
    'fi': 'fin', 'fil': 'fil', 'fr': 'fre', 'gl': 'glg', 'gu': 'guj', 'he': 'heb', 'hi': 'hin', 'hr': 'hrv',
    'hu': 'hun', 'hy': 'arm', 'id': 'ind', 'is': 'ice', 'it': 'ita', 'ja': 'jpn', 'jv': 'jav', 'ka': 'geo',
    'km': 'khm', 'kn': 'kan', 'ko': 'kor', 'lo': 'lao', 'lt': 'lit', 'lv': 'lav', 'ml': 'mal', 'mr': 'mar',
    'ms': 'may', 'nb': 'nob', 'ne': 'nep', 'nl': 'dut', 'pl': 'pol', 'pt': 'por', 'ro': 'rum', 'ru': 'rus',
    'si': 'sin', 'sk': 'slo', 'sl': 'slv', 'sr': 'srp', 'su': 'sun', 'sv': 'swe', 'sw': 'swa', 'ta': 'tam',
    'te': 'tel', 'th': 'tha', 'tr': 'tur', 'uk': 'ukr', 'ur': 'urd', 'vi': 'vie', 'yue': 'chi', 'zu': 'zul',
}
_TERMINOLOGIC = {'ces': 'cs', 'deu': 'de', 'ell': 'el', 'eus': 'eu', 'fas': 'fa', 'fra': 'fr', 'hye': 'hy',
                 'isl': 'is', 'kat': 'ka', 'msa': 'ms', 'nld': 'nl', 'ron': 'ro', 'slk': 'sk', 'zho': 'cmn',
                 'nor': 'nb', 'nno': 'nb'}
FROM_ISO639_2 = dict({three: two for two, three in ISO639_2.items() if two != 'yue'}, **_TERMINOLOGIC)


def iso639_2(code):
    """The ISO 639-2 code for a language as Subtitld names it ("pt-br" is
    "por"); its own first part when there is none."""
    primary = str(code or '').replace('_', '-').split('-')[0].lower()
    return ISO639_2.get(primary, primary)


def _usf_color(value):
    """'#rrggbb' for a USF colour ("#AARRGGBB", "#RRGGBB" or a name), or ''."""
    value = str(value or '').strip()
    if value.startswith('#') and len(value) == 9:
        value = '#' + value[3:]
    return markup.color_hex(value)


def _inline_text(tag):
    """The text of an element as tags: its inline formatting kept, <br/> a line break."""
    parts = []
    for child in tag.children:
        if isinstance(child, NavigableString):
            parts.append(str(child))
        elif child.name == 'br':
            parts.append('\n')
        elif child.name in _INLINE:
            parts.append(f'<{child.name}>' + _inline_text(child) + f'</{child.name}>')
        elif child.name == 'font':
            # Its colour, and the italic, weight and underline USF's plans
            # give it and some tools write.
            opening, closing = '', ''
            if _usf_color(child.get('color')):
                opening, closing = f'<font color="{_usf_color(child.get("color"))}">', '</font>'
            for name, on in (('i', _yes(child.get('italic'))), ('b', _bold(child)), ('u', _yes(child.get('underline')))):
                if on:
                    opening, closing = opening + f'<{name}>', f'</{name}>' + closing
            parts.append(opening + _inline_text(child) + closing)
        else:
            parts.append(_inline_text(child))
    return ''.join(parts)


def _yes(value):
    return str(value or '').strip().lower() in ('yes', 'true', '1')


def _bold(element):
    """Whether a <font> or <fontstyle> is bold: bold="yes", or a weight of
    bold, bolder or 600 and more."""
    weight = str(element.get('weight') or '').strip().lower()
    return _yes(element.get('bold')) or weight in ('bold', 'bolder') or (weight.isdigit() and int(weight) >= 600)


def _extract_inline_text(tag, style=None):
    """Return the text of a <text> element: its formatting as tags, its
    position as an {\\anN} code before them. `style`, the named style it
    uses ({'italic', 'bold', 'underline', 'color', 'alignment'}), formats
    all of it, and places it where the text says nowhere."""
    text = _inline_text(tag).strip()
    style = style or {}
    for name in ('u', 'b', 'i'):
        if style.get({'i': 'italic', 'b': 'bold', 'u': 'underline'}[name]):
            text = f'<{name}>{text}</{name}>'
    if style.get('color'):
        text = f'<font color="{style["color"]}">{text}</font>'
    if style:
        text = markup.from_spans(markup.spans(text))
    alignment = str(tag.get('alignment') or style.get('alignment') or '').lower()
    keypad = {name.lower(): key for key, name in markup.KEYPAD_NAMES.items()}.get(alignment)
    if keypad and keypad != 2:
        text = markup.with_alignment('', keypad) + text
    return text


def format_time(seconds):
    """USF time for ``seconds``: "HH:MM:SS.mmm", to the nearest millisecond."""
    total = max(0, int(round(float(seconds) * 1000)))
    hours, rest = divmod(total, 3600000)
    minutes, rest = divmod(rest, 60000)
    secs, millis = divmod(rest, 1000)
    return f'{hours:02d}:{minutes:02d}:{secs:02d}.{millis:03d}'


def parse_time(text):
    """Seconds from a USF time ("HH:MM:SS.mmm"; hours and minutes may be left out, the fraction may have
    any number of digits). Subtitld used to write times 1 ms early, and a start of 0 as 23:59:59.999:
    that value reads as 0 again; the 1 ms is left as it is."""
    text = str(text).strip()
    if text == '23:59:59.999':
        return 0.0
    whole, _dot, fraction = text.partition('.')
    seconds = 0
    for part in whole.split(':'):
        seconds = seconds * 60 + int(part or 0)
    millis = int(round(float('0.' + fraction) * 1000)) if fraction else 0
    return (seconds * 1000 + millis) / 1000


def _parse_numeric(value, caster):
    try:
        return caster(value)
    except (TypeError, ValueError):
        return None


class USFReader():
    """USFReader class. `language_of(code, name)` gives the code a
    language's block and translations go by (by default its code)."""
    def __init__(self, *args, language_of=None, **kwargs):
        super(USFReader, self).__init__(*args, **kwargs)
        self.language_of = language_of or (lambda code, name: code)
        self.metadata = {}
        self.language = None
        self.speakers = {}  # name -> {'color': '#RRGGBB'}
        self.origin = None  # {'share_id', 'version'} when the file came from subtitld.cc
        self.has_embedded_images = False
        self.has_embedded_audio_clips = False
        self._styles = {}   # name -> {'italic', 'bold', 'underline', 'color', 'alignment'}

    def detect(self, content):
        """Function to return if this is a USF file"""
        return '<usfsubtitles' in content.lower()

    def read(self, content):
        """Parse USF content (bytes, read in the encoding the XML declares,
        or text) and return a list of subtitle dicts.

        Populates self.metadata, self.language and self.speakers as a side
        effect so the caller can reflect title/author/date/language and the
        per-speaker colors back into session state. Raises ValueError for
        a document that is not USF.
        """
        self.metadata = {}
        self.language = None
        self.speakers = {}
        self.origin = None
        self.has_embedded_images = False
        self.has_embedded_audio_clips = False
        self._styles = {}

        soup = BeautifulSoup(content, features="xml")
        if soup.find('USFSubtitles') is None:
            root = next((tag.name for tag in soup.find_all(True, limit=1)), None)
            raise ValueError(f'Not a USF document: it is <{root}>, not <USFSubtitles>' if root else
                             'Not a USF document: there is no XML in it')

        meta = soup.find('metadata')
        if meta:
            for key in ('title', 'date'):
                tag = meta.find(key)
                if tag and tag.text:
                    self.metadata[key] = tag.text.strip()
            lang = meta.find('language', recursive=False)
            if lang and lang.attrs.get('code'):
                self.language = self.language_of(lang.attrs['code'], lang.text.strip())
            author = meta.find('author')
            if author:
                name = author.find('name')
                if name and name.text:
                    self.metadata['author'] = name.text.strip()
            origin = meta.find('origin')
            if origin is not None and origin.namespace == SUBTITLDCC_NAMESPACE and origin.attrs.get('share-id'):
                self.origin = {
                    'share_id': origin.attrs['share-id'],
                    'version': _parse_numeric(origin.attrs.get('version'), int),
                }

        for style in soup.select('styles > style'):
            name = style.attrs.get('name')
            if not name:
                continue
            # How the style formats and places a text that uses it.
            look = {}
            fontstyle = style.find('fontstyle')
            if fontstyle is not None:
                look = {'italic': _yes(fontstyle.get('italic')), 'bold': _bold(fontstyle),
                        'underline': _yes(fontstyle.get('underline')), 'color': _usf_color(fontstyle.get('color'))}
                if look['color'] == '#ffffff':
                    look['color'] = ''
            position = style.find('position')
            if position is not None and position.get('alignment'):
                look['alignment'] = position.get('alignment')
            self._styles[name] = {key: value for key, value in look.items() if value}
            if name == 'Default':
                continue
            entry = {}
            fontstyle = style.find('fontstyle')
            if fontstyle and fontstyle.attrs.get('color'):
                entry['color'] = fontstyle.attrs['color']
            avatar = style.find('avatar')
            if avatar and avatar.attrs.get('encoding') == 'base64' and avatar.text:
                try:
                    entry['image_bytes'] = base64.b64decode(avatar.text.strip())
                    self.has_embedded_images = True
                except Exception:
                    pass
            dub_elem = style.find('dubbing')
            if dub_elem:
                dub_data = {}
                for key in ('engine', 'voice'):
                    if key in dub_elem.attrs:
                        dub_data[key] = dub_elem.attrs[key]
                for key in ('rate', 'pitch'):
                    if key in dub_elem.attrs:
                        parsed = _parse_numeric(dub_elem.attrs[key], int)
                        if parsed is not None:
                            dub_data[key] = parsed
                # "Fit dub to subtitle duration". Absent means off, which is
                # what every project saved before the flag existed holds.
                if 'fit_to_subtitle' in dub_elem.attrs:
                    dub_data['fit_to_subtitle'] = (
                        str(dub_elem.attrs['fit_to_subtitle']).strip().lower() in ('true', '1', 'yes'))
                if dub_data:
                    entry['dubbing'] = dub_data
            if entry:
                self.speakers[name] = entry

        blocks = soup.find_all('subtitles')
        if not blocks:
            return []

        primary_block = blocks[0]
        primary_lang = self._block_language(primary_block)
        if primary_lang and not self.language:
            self.language = primary_lang

        subtitles_list = []
        for element in primary_block.find_all('subtitle', recursive=False):
            entry = self._parse_subtitle(element)
            if entry:
                subtitles_list.append(entry)
        subtitles_list.sort(key=lambda sub: sub['start'])

        # Each other language's subtitles go to the first's that start with
        # them (as Subtitld writes them), else the ones they overlap most:
        # blocks need not hold the same number.
        by_start = {}
        for primary_sub in subtitles_list:
            by_start.setdefault(round(primary_sub['start'], 3), primary_sub)
        ordered = sorted(subtitles_list, key=lambda sub: sub['start'])
        starts = [sub['start'] for sub in ordered]

        def overlap(primary_sub, other):
            return min(primary_sub['end'], other['end']) - max(primary_sub['start'], other['start'])

        for block in blocks[1:]:
            lang = self._block_language(block)
            if not lang:
                continue
            for tr_sub in block.find_all('subtitle', recursive=False):
                translated = self._parse_subtitle(tr_sub, dubs=False)
                if not translated or not translated['text']:
                    continue
                best = by_start.get(round(translated['start'], 3))
                if best is None:
                    nearby = ordered[max(0, bisect.bisect_right(starts, translated['start']) - 1):
                                     bisect.bisect_left(starts, translated['end'])]
                    best = max(nearby, key=lambda sub: overlap(sub, translated), default=None)
                    if best is not None and overlap(best, translated) <= 0:
                        best = None
                if best is not None:
                    translations = best.setdefault('translations', {})
                    translations[lang] = (translations[lang] + '\n' + translated['text']) if translations.get(lang) \
                        else translated['text']

        return subtitles_list

    def _block_language(self, block):
        lang = block.find('language')
        if lang and lang.attrs.get('code'):
            return self.language_of(lang.attrs['code'], lang.text.strip())
        return None

    def _parse_subtitle(self, element, dubs=True):
        if 'start' not in element.attrs:
            return None
        start = parse_time(element.attrs['start'])
        if 'stop' in element.attrs:
            end = parse_time(element.attrs['stop'])
        elif 'duration' in element.attrs:
            end = start + parse_time(element.attrs['duration'])
        else:
            return None

        subtitle = {'start': start, 'end': max(start, round(end, 3))}
        if element.attrs.get(SUBTITLDCC_ID):
            subtitle['id'] = element.attrs[SUBTITLDCC_ID]

        # Its texts, each formatted by the named style it uses unless that
        # style is its speaker's, as Subtitld names them (that one gives the
        # speaker's colour, not the text's).
        texts, speaker = [], None
        for text_tag in element.find_all(['text', 'karaoke'], recursive=False):
            speaker = speaker or text_tag.attrs.get('speaker')
            style_name = text_tag.attrs.get('style')
            style = self._styles.get(style_name) if style_name and style_name != text_tag.attrs.get('speaker') else None
            texts.append(_extract_inline_text(text_tag, style))
        # One place for them all: the first text's.
        lead = markup.split_lead(texts[0])[0] if texts else ''
        subtitle['text'] = lead + '\n'.join(markup.split_lead(text)[1] for text in texts if text)
        subtitle['speaker'] = speaker or 'A'
        if not dubs:
            return subtitle

        dubs = []
        for dub_elem in element.find_all('dubbing', recursive=False):
            dub = {}
            for key, value in dub_elem.attrs.items():
                dub[key] = value
            for key in ('start', 'end'):
                if key in dub:
                    parsed = _parse_numeric(dub[key], float)
                    if parsed is not None:
                        dub[key] = parsed
            for key in ('rate', 'pitch'):
                if key in dub:
                    parsed = _parse_numeric(dub[key], int)
                    if parsed is not None:
                        dub[key] = parsed
            data_tag = dub_elem.find('data')
            if data_tag and data_tag.attrs.get('encoding') == 'base64' and data_tag.text:
                try:
                    dub['_embedded_bytes'] = base64.b64decode(data_tag.text.strip())
                    dub['_embedded_format'] = data_tag.attrs.get('format', 'wav')
                    self.has_embedded_audio_clips = True
                except Exception:
                    pass
            # Per-subclip data (independent subclips schema — see
            # dub_clip.py). Each <subclip> carries source coords (start,
            # end), timeline offset (offset), and an optional rate/raw_path
            # for ffmpeg-stretched subclips. Without persisting these the
            # split/stretch a user did is silently discarded on reload.
            segs = []
            for seg_elem in dub_elem.find_all('subclip', recursive=False):
                seg = {}
                for key, value in seg_elem.attrs.items():
                    seg[key] = value
                for key in ('start', 'end', 'offset'):
                    if key in seg:
                        parsed = _parse_numeric(seg[key], float)
                        if parsed is not None:
                            seg[key] = parsed
                if 'rate' in seg:
                    parsed = _parse_numeric(seg['rate'], int)
                    if parsed is not None:
                        seg['rate'] = parsed
                seg.setdefault('type', 'audio')
                segs.append(seg)
            if segs:
                dub['segments'] = segs
            dubs.append(dub)
        if dubs:
            subtitle['dubbing'] = dubs

        return subtitle


class USFWriter():
    """USFWriter class"""
    def __init__(self, *args, **kwargs):
        super(USFWriter, self).__init__(*args, **kwargs)

    def write(self, subtitles, speakers=None, language=None, metadata=None,
              embed_audio_clips=False, origin=None, names=None):
        """Serialize subtitles to USF XML.

        Parameters:
          subtitles: list of subtitle dicts (from session.SUBTITLE['segments']).
          speakers:  dict name -> {'color': '#RRGGBB', 'image_bytes': bytes, ...}.
                     Emits one <style> per speaker; writes `speaker` + `style` on
                     <text>. If a speaker has `image_bytes`, embeds it inside the
                     <style> as <avatar encoding="base64" format="png">…</avatar>.
          language:  ISO language code for the primary <subtitles> block.
          metadata:  dict with optional 'title', 'author', 'date' keys.
          embed_audio_clips: if True, reads each dub's WAV file from disk and
                     embeds base64 bytes as <data encoding="base64"> inside the
                     <dubbing> element.
          origin:    {'share_id', 'version'} of the subtitld.cc subtitle this
                     came from, so it can be published back as a new version.
          names:     {Subtitld's language code: its name}, written as each
                     <language>'s text beside its ISO 639-2 code.
        """
        speakers = speakers or {}
        metadata = metadata or {}
        names = names or {}

        def language_tag(code):
            tag = usf.new_tag('language')
            tag['code'] = iso639_2(code)
            name = names.get(code) or names.get(str(code).lower().replace('_', '-'))
            if name:
                tag.string = name
            return tag

        usf = BeautifulSoup(USF_BASE_MARKUP, 'lxml-xml')

        meta_tag = usf.find('metadata')
        if 'title' in metadata:
            title = usf.new_tag('title')
            title.string = str(metadata['title'])
            meta_tag.append(title)
        author = usf.new_tag('author')
        name = usf.new_tag('name')
        name.string = str(metadata.get('author', 'Subtitld'))
        author.append(name)
        meta_tag.append(author)
        if language:
            meta_tag.append(language_tag(language))
        if 'date' in metadata:
            date = usf.new_tag('date')
            date.string = str(metadata['date'])
            meta_tag.append(date)
        if (origin and origin.get('share_id')) or any(subtitle.get('id') for subtitle in subtitles):
            usf.find('USFSubtitles')['xmlns:subtitldcc'] = SUBTITLDCC_NAMESPACE
        if origin and origin.get('share_id'):
            origin_tag = usf.new_tag('origin', namespace=SUBTITLDCC_NAMESPACE, nsprefix='subtitldcc')
            origin_tag['share-id'] = origin['share_id']
            if origin.get('version') is not None:
                origin_tag['version'] = str(origin['version'])
            meta_tag.append(origin_tag)

        # No "Default" style: one would override the player's own look for
        # every subtitle (Subtitld's used to be pale blue, outlined in blue).
        styles_tag = usf.find('styles')

        for speaker_name, speaker_data in speakers.items():
            if speaker_name == 'Default':
                continue
            style = usf.new_tag('style')
            style['name'] = speaker_name
            color = speaker_data.get('color') if isinstance(speaker_data, dict) else None
            if color:
                fontstyle = usf.new_tag('fontstyle')
                fontstyle['color'] = color
                style.append(fontstyle)
            image_bytes = speaker_data.get('image_bytes') if isinstance(speaker_data, dict) else None
            if image_bytes:
                avatar = usf.new_tag('avatar')
                avatar['encoding'] = 'base64'
                avatar['format'] = 'png'
                avatar.string = base64.b64encode(image_bytes).decode('ascii')
                style.append(avatar)
            dubbing_settings = speaker_data.get('dubbing') if isinstance(speaker_data, dict) else None
            if isinstance(dubbing_settings, dict):
                dub_tag = usf.new_tag('dubbing')
                for key in ('engine', 'voice'):
                    val = dubbing_settings.get(key)
                    if val:
                        dub_tag[key] = str(val)
                for key in ('rate', 'pitch'):
                    val = dubbing_settings.get(key)
                    if val is not None:
                        dub_tag[key] = str(val)
                # Written only when on, so files without the setting stay
                # byte-for-byte what they were.
                if dubbing_settings.get('fit_to_subtitle'):
                    dub_tag['fit_to_subtitle'] = 'true'
                if dub_tag.attrs:
                    style.append(dub_tag)
            styles_tag.append(style)

        primary = usf.new_tag('subtitles')
        if language:
            primary.append(language_tag(language))
        usf.find('USFSubtitles').append(primary)

        for subtitle in subtitles:
            primary.append(self._build_subtitle(usf, subtitle, speakers, embed_audio_clips=embed_audio_clips))

        translation_languages = []
        for subtitle in subtitles:
            for lang in subtitle.get('translations', {}):
                if lang and lang not in translation_languages and lang != language:
                    translation_languages.append(lang)

        for tr_lang in translation_languages:
            block = usf.new_tag('subtitles')
            block.append(language_tag(tr_lang))
            for subtitle in subtitles:
                block.append(self._build_subtitle(
                    usf,
                    subtitle,
                    speakers,
                    text_override=subtitle.get('translations', {}).get(tr_lang, ''),
                    include_dubs=False,
                ))
            usf.find('USFSubtitles').append(block)

        return str(usf)

    def _build_subtitle(self, usf, subtitle, speakers, text_override=None, include_dubs=True, embed_audio_clips=False):
        new_sub = usf.new_tag(
            'subtitle',
            start=format_time(subtitle['start']),
            stop=format_time(subtitle['end']),
        )
        # Only in the language's own block: a translation's block repeats its
        # subtitles, and is matched to them by time when read.
        if text_override is None and subtitle.get('id'):
            new_sub[SUBTITLDCC_ID] = subtitle['id']

        text_tag = usf.new_tag('text')
        speaker = subtitle.get('speaker', 'A')
        if speaker:
            text_tag['speaker'] = speaker
            if speaker in speakers:
                text_tag['style'] = speaker

        text_value = subtitle.get('text', '') if text_override is None else text_override
        self._append_text_with_breaks(usf, text_tag, text_value)
        new_sub.append(text_tag)

        if include_dubs:
            for dub in subtitle.get('dubbing', []):
                dub_tag = usf.new_tag('dubbing')
                for key in ('engine', 'path', 'uid', 'voice', 'raw_path'):
                    if key in dub and dub[key] is not None:
                        dub_tag[key] = str(dub[key])
                for key in ('start', 'end', 'rate', 'pitch'):
                    if key in dub and dub[key] is not None:
                        dub_tag[key] = str(dub[key])
                # Persist independent subclips (the split/stretch list).
                # Without these elements the schema collapses on reload to
                # a single subclip synthesised from `dub['path']` — every
                # split or per-subclip stretch the user made is lost.
                for seg in dub.get('segments', []) or []:
                    seg_tag = usf.new_tag('subclip')
                    for key in ('type', 'path', 'raw_path'):
                        if key in seg and seg[key] is not None:
                            seg_tag[key] = str(seg[key])
                    for key in ('start', 'end', 'offset'):
                        if key in seg and seg[key] is not None:
                            seg_tag[key] = str(seg[key])
                    if seg.get('rate') is not None:
                        seg_tag['rate'] = str(seg['rate'])
                    dub_tag.append(seg_tag)
                if embed_audio_clips:
                    path = dub.get('path')
                    if path and os.path.isfile(path):
                        try:
                            with open(path, 'rb') as f:
                                raw = f.read()
                            data_tag = usf.new_tag('data')
                            data_tag['encoding'] = 'base64'
                            data_tag['format'] = os.path.splitext(path)[1].lstrip('.').lower() or 'wav'
                            data_tag.string = base64.b64encode(raw).decode('ascii')
                            dub_tag.append(data_tag)
                        except Exception:
                            pass
                new_sub.append(dub_tag)

        return new_sub

    def _append_text_with_breaks(self, usf, text_tag, value):
        """The text into `text_tag` as USF writes it: formatting as inline
        elements, line breaks as <br/>, the position as "alignment". Other
        override codes it starts with stay as they are written."""
        if not value:
            return
        lead, rest = markup.split_lead(str(value))
        keypad = markup.alignment(lead)
        if keypad != 2:
            text_tag['alignment'] = markup.KEYPAD_NAMES[keypad]
        other = markup.with_alignment(lead, 2)
        if other:
            text_tag.append(NavigableString(other))
        stack = []                                    # [((name, value), element)]
        for run, style in markup.spans(rest):
            wanted = markup.tags_for(style)
            keep = 0
            while keep < len(stack) and stack[keep][0] in wanted:
                keep += 1
            del stack[keep:]
            kept = [item for item, _element in stack]
            for item in sorted((item for item in wanted if item not in kept), key=lambda item: markup.TAG_ORDER.index(item[0])):
                element = usf.new_tag('font', attrs={'color': item[1]}) if item[0] == 'font' else usf.new_tag(item[0])
                (stack[-1][1] if stack else text_tag).append(element)
                stack.append((item, element))
            parent = stack[-1][1] if stack else text_tag
            for index, line in enumerate(run.split('\n')):
                if index:
                    parent.append(usf.new_tag('br'))
                if line:
                    parent.append(NavigableString(line))
